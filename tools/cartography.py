note = '终点取校图可辨认的楼旁步道，具体楼门与通行以现场为准。'

def place(ident, name, category, zone, point, access, footprint, description, *, short=None, aliases=(), shape=True, access_note=note, tone=None):
    item = dict(id=ident,name=name,shortName=short or name,category=category,zone=zone,
                official=list(point),access=list(access),footprint=footprint,aliases=list(aliases),
                description=description,accessNote=access_note)
    places.append(item)
    if shape: structures.append((ident,tone or category,footprint))
    return item

